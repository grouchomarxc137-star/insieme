import { useEffect, useState } from 'react';
import PlantScene from '../components/PlantScene.jsx';
import {
  useGrowth,
  levelProgress,
  stageForLevel,
  STAGES,
  MAX_LEVEL,
  QUICK_LOGS,
  getQuickLogConfirmations,
  confirmQuickLog,
  removeQuickLogConfirmation,
  currentMultiplier,
  MULTIPLIER_FLOOR,
  MULTIPLIER_SPAN,
} from '../lib/growth.js';
import './PlantPage.css';

const PARTICIPANTS = ['Principe', 'Principessa'];

const FACTORS = [
  {
    id: 'water',
    icon: '💧',
    label: 'Water',
    color: 'var(--water)',
    what: "How consistently you're each showing up for yourselves, day to day.",
    affects: 'Rises when you complete your personal daily tasks. Drifts down if personal tasks go unfinished for several days in a row.',
    irl: "Watering is the unglamorous stuff — sleep, movement, working on your own things. A relationship dries out fastest when the people in it are running on empty.",
  },
  {
    id: 'sun',
    icon: '☀️',
    label: 'Sun',
    color: 'var(--gold)',
    what: 'The warmth generated by showing up for each other every day.',
    affects: "Rises when you complete your daily relationship tasks. Fades if they're skipped for a stretch.",
    irl: 'Sunlight here is daily connection — a real conversation, a kind text, actually asking how their day went. Small and constant beats big and rare.',
  },
  {
    id: 'air',
    icon: '🍃',
    label: 'Air quality',
    color: 'var(--mint-strong)',
    what: "How clear things are between you right now.",
    affects: 'Drops the longer a ticket sits open and unresolved. Opening a ticket never hurts this — only letting it sit does.',
    irl: 'This tracks unspoken friction. Small things left unsaid pile up like smog; naming them early keeps the air clear.',
    notWiredYet: 'Tickets isn\'t a real feature yet, so this only moves when you log a resolved ticket by hand, below.',
  },
  {
    id: 'toxicity',
    icon: '🌫️',
    label: 'Toxicity',
    color: 'var(--toxicity)',
    what: 'How much unresolved conflict is sitting under the surface.',
    affects: 'Rises if a real conflict goes unaddressed for a long time. Falls once a Reset Room session actually finishes, not just starts.',
    irl: 'Using the Reset Room is never what raises this — avoiding it is. This tracks whether disagreements get closed out, not swept aside.',
    notWiredYet: 'Reset Room isn\'t a real feature yet, so this only moves when you log a finished session by hand, below.',
  },
  {
    id: 'bees',
    icon: '🐝',
    label: 'Bees',
    color: 'var(--gold-strong)',
    what: 'The bigger, occasional efforts that cross-pollinate everything else.',
    affects: 'Rises with monthly relationship goals and check-ins completed. These move slower than daily tasks but count for more.',
    irl: 'Bees are the date nights, the planned goals, the sit-down conversations you schedule on purpose — less frequent, but what actually spreads growth around.',
  },
];

export default function PlantPage({ user }) {
  const otherName = user === 'Principe' ? 'Principessa' : 'Principe';
  const growth = useGrowth();
  const multiplier = currentMultiplier(growth);
  const multiplierPct = Math.round(((multiplier - MULTIPLIER_FLOOR) / MULTIPLIER_SPAN) * 100);
  const { level, isMax, xpIntoLevel, xpForNext } = levelProgress(growth.totalXp);
  const currentStage = stageForLevel(level);
  const currentIndex = STAGES.findIndex((stage) => stage.id === currentStage.id);
  const nextStage = STAGES[currentIndex + 1];
  const levelsToNext = nextStage ? nextStage.minLevel - level : 0;

  const [openFactorId, setOpenFactorId] = useState(null);
  const openFactor = FACTORS.find((factor) => factor.id === openFactorId) || null;

  function handleQuickLog(entry) {
    confirmQuickLog(user, entry);
    growth.refresh();
  }

  function handleRemoveConfirmation(entryId, side) {
    removeQuickLogConfirmation(entryId, side);
    growth.refresh();
  }

  useEffect(() => {
    if (!openFactor) return undefined;
    function handleKeyDown(event) {
      if (event.key === 'Escape') setOpenFactorId(null);
    }
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [openFactor]);

  return (
    <div className="page">
      <div className="page-header">
        <h1>Plant</h1>
        <p>Water, Sun, and Bees grow from real tasks. Log a check-in, Reset Room, or resolved ticket below to move Air and Toxicity too.</p>
      </div>

      <div className="scene-card">
        <PlantScene className="plant-scene-svg" stage={currentIndex + 1} />
      </div>

      <div className="growth-card">
        <div className="level-row">
          <span className="lock-badge lock-badge--locked">Lv. {level} / {MAX_LEVEL}</span>
          <span className="level-stage-name">{currentStage.icon} {currentStage.label}</span>
        </div>
        <div className="level-bar">
          <div className="level-bar-fill" style={{ width: `${(level / MAX_LEVEL) * 100}%` }} />
        </div>
        <p className="level-hint">
          {isMax
            ? 'Fully grown — the highest stage.'
            : `${xpIntoLevel} / ${xpForNext} XP to Lv. ${level + 1}${
                nextStage ? ` · ${levelsToNext} level${levelsToNext === 1 ? '' : 's'} to ${nextStage.label}` : ''
              }`}
        </p>

        <div className="multiplier-row">
          <span className="multiplier-label">⚡ Growth multiplier</span>
          <span className="multiplier-value">{multiplier}x</span>
        </div>
        <div className="level-bar multiplier-bar">
          <div className="level-bar-fill multiplier-bar-fill" style={{ width: `${multiplierPct}%` }} />
        </div>
        <p className="level-hint">
          Every XP award gets scaled by this — 0.6x when the elements are neglected, up to 1.5x when they're healthy.
          It's the average of Water, Sun, Air, Bees, and (100 − Toxicity).
        </p>

        <h2>Growth roadmap</h2>
        <div className="growth-track">
          {STAGES.map((stage, index) => (
            <div key={stage.id} className="growth-step-wrap">
              <div
                className={`growth-step${index === currentIndex ? ' is-current' : ''}${
                  index < currentIndex ? ' is-past' : ''
                }`}
              >
                <span className="growth-icon">{stage.icon}</span>
                <span className="growth-label">{stage.label}</span>
                <span className="growth-level">
                  Lv. {stage.minLevel}–{stage.maxLevel}
                </span>
              </div>
              {index < STAGES.length - 1 && <span className="growth-arrow">›</span>}
            </div>
          ))}
        </div>
      </div>

      <div className="factors-card">
        <h2>What's feeding it</h2>
        <p className="factors-hint">Tap any factor to see what it is and what moves it.</p>
        <div className="factor-list">
          {FACTORS.map((factor) => {
            const value = Math.round(growth[factor.id]);
            return (
              <button
                type="button"
                className="factor-row"
                key={factor.id}
                onClick={() => setOpenFactorId(factor.id)}
              >
                <span className="factor-icon">{factor.icon}</span>
                <span className="factor-label">{factor.label}</span>
                <div className="factor-bar">
                  <div
                    className="factor-bar-fill"
                    style={{ width: `${value}%`, background: factor.color }}
                  />
                </div>
                <span className="factor-value">{value}%</span>
              </button>
            );
          })}
        </div>
      </div>

      <div className="factors-card">
        <h2>Log it</h2>
        <p className="factors-hint">
          For the parts that aren't real features yet — tap when it actually happened. Always available; the XP
          only lands once both of you have confirmed the same one.
        </p>
        <div className="factor-list">
          {QUICK_LOGS.map((entry) => {
            const confirmations = getQuickLogConfirmations(entry.id);
            const youConfirmed = Boolean(confirmations[user]);
            const otherConfirmed = Boolean(confirmations[otherName]);
            let status = `+${entry.xp} XP`;
            if (youConfirmed && !otherConfirmed) status = `Waiting on ${otherName}`;
            else if (otherConfirmed && !youConfirmed) status = `${otherName} confirmed — tap to match`;
            return (
              <div key={entry.id} className="quick-log-row">
                <button type="button" className="quick-log-main" onClick={() => handleQuickLog(entry)}>
                  <span className="factor-icon">{entry.icon}</span>
                  <span className="quick-log-body">
                    <span className="factor-label quick-log-label">{entry.label}</span>
                    <span className="quick-log-description">{entry.description}</span>
                  </span>
                  <span className="quick-log-status">{status}</span>
                </button>
                <div className="quick-log-sides">
                  {PARTICIPANTS.map((side) => {
                    const confirmed = Boolean(confirmations[side]);
                    return (
                      <span key={side} className={`quick-log-side${confirmed ? ' is-confirmed' : ''}`}>
                        {side} {confirmed ? '✓' : '—'}
                        {confirmed && (
                          <button
                            type="button"
                            className="quick-log-side-remove"
                            aria-label={`Remove ${side}'s confirmation for "${entry.label}"`}
                            onClick={() => handleRemoveConfirmation(entry.id, side)}
                          >
                            ✕
                          </button>
                        )}
                      </span>
                    );
                  })}
                </div>
              </div>
            );
          })}
        </div>
      </div>

      {openFactor && (
        <div className="factor-modal-backdrop" onClick={() => setOpenFactorId(null)}>
          <div className="factor-modal" onClick={(event) => event.stopPropagation()}>
            <button
              type="button"
              className="factor-modal-close"
              onClick={() => setOpenFactorId(null)}
              aria-label="Close"
            >
              ✕
            </button>
            <div className="factor-modal-header">
              <span className="factor-modal-icon">{openFactor.icon}</span>
              <h2>{openFactor.label}</h2>
              <span className="factor-modal-value">{Math.round(growth[openFactor.id])}%</span>
            </div>
            {openFactor.notWiredYet && (
              <div className="factor-modal-section">
                <h3>Status</h3>
                <p>{openFactor.notWiredYet}</p>
              </div>
            )}
            <div className="factor-modal-section">
              <h3>What it is</h3>
              <p>{openFactor.what}</p>
            </div>
            <div className="factor-modal-section">
              <h3>What affects it</h3>
              <p>{openFactor.affects}</p>
            </div>
            <div className="factor-modal-section">
              <h3>What it means IRL</h3>
              <p>{openFactor.irl}</p>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
